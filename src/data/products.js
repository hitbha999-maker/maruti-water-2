export const bySection = (id) => products.filter((p) => p.section === id)

/* Rated capacity in litres per hour.

   The model name is the authority: the catalogue prints "LTR" where it means
   litres per hour, and on two plant pages the spec block repeats the previous
   model's figure (the 150 LPH plant is printed as "100 to 110 Ltr."). Where the
   name carries no number - the domestic cabinets - fall back to the spec. */
export function capacityLph(p) {
  const fromName = p.name.match(/(\d[\d,]*)\s*(?:LPH|LTR|L)\b/i)
  if (fromName) return Number(fromName[1].replace(/,/g, ''))
  const nums = (p.specs['Purification Capacity'] || '').match(/\d+/g)
  return nums ? Math.max(...nums.map(Number)) : 0
}

/* ---------- Requirement finder ----------
   Maps a stated daily requirement onto the catalogue. Capacity is treated as a
   hard constraint: a unit that cannot keep up is never recommended, however
   well it matches on everything else. Where nothing in the preferred range is
   big enough, the next range up is allowed through rather than proposing an
   undersized system. */
export function recommend({ setting, litresPerDay, needs }) {
  const hoursPerDay = setting === 'home' ? 6 : 8
  const requiredLph = Math.max(1, Math.ceil(litresPerDay / hoursPerDay))

  const preferred =
    setting === 'home'
      ? ['domestic', 'commercial']
      : setting === 'business'
        ? ['commercial', 'industrial', 'domestic']
        : ['industrial', 'commercial']

  const scored = products.map((p) => {
    const lph = capacityLph(p)
    let score = 0
    const notes = []

    if (lph < requiredLph) {
      // Ranked by how close it gets, so the fallback list still reads sensibly.
      const shortfall = (requiredLph - lph) / requiredLph
      score -= 200 + Math.round(shortfall * 100)
    } else {
      score += 40
      const headroom = lph / requiredLph
      if (headroom > 6) score -= 30
      else if (headroom > 3) score -= 12
      else notes.push(`${lph} LPH keeps up with ${litresPerDay} litres a day`)
    }

    const rank = preferred.indexOf(p.section)
    score += rank === 0 ? 30 : rank === 1 ? 12 : rank === 2 ? 2 : -40

    needs.forEach((n) => {
      if (n === 'alkaline' && /ALKALINE/i.test(p.configuration)) {
        score += 14
        notes.push('Alkaline cartridge included')
      }
      if (n === 'uv' && p.cartridges.some((c) => /UV/i.test(c))) {
        score += 14
        notes.push('UV lamp fitted')
      }
      if (n === 'tds' && p.cartridges.some((c) => /TDS/i.test(c))) {
        score += 12
        notes.push('TDS controller fitted')
      }
      if (n === 'steel' && /Stainless/i.test(p.specs['Body Materials'] || '')) {
        score += 12
        notes.push('Stainless steel body')
      }
      if (n === 'budget' && p.price) score += Math.max(0, 14 - p.price / 12000)
    })

    if (p.price === null) score -= 6

    return { product: p, score, lph, requiredLph, notes: notes.slice(0, 3) }
  })

  return scored.sort((a, b) => b.score - a.score).slice(0, 3)
}

